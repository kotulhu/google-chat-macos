    /// Emojis matching a query by glyph or by CLDR keyword.  Empty query
    /// returns nothing (the caller shows the category browser instead).
    static func matches(_ query: String) -> [String] {
        let needle = query.lowercased().trimmingCharacters(in: .whitespaces)
        guard !needle.isEmpty else { return [] }
        var results: [String] = []
        var seen = Set<String>()
        for category in categories {
            for emoji in category.emojis where !seen.contains(emoji) {
                seen.insert(emoji)
                if emoji.contains(needle) || (keywords[emoji]?.contains(needle) ?? false) {
                    results.append(emoji)
                }
            }
        }
        return results
    }
